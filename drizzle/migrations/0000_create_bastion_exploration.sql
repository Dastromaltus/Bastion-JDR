CREATE TABLE public.exploration_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  map_key TEXT NOT NULL DEFAULT 'sector-01',
  objective TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'exploration' CHECK (status IN ('exploration', 'combat', 'complete')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
GRANT SELECT ON public.exploration_sessions TO anon, authenticated;
GRANT ALL ON public.exploration_sessions TO service_role;
ALTER TABLE public.exploration_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Exploration sessions are publicly visible" ON public.exploration_sessions FOR SELECT TO anon, authenticated USING (true);

CREATE TABLE public.exploration_players (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id UUID NOT NULL REFERENCES public.exploration_sessions(id) ON DELETE CASCADE,
  client_key TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT 'Éclaireur',
  race TEXT NOT NULL DEFAULT 'Humain' CHECK (race IN ('Humain', 'Insecte', 'Reptile', 'Crustacé', 'Oiseau')),
  tile_x INTEGER NOT NULL DEFAULT 2,
  tile_y INTEGER NOT NULL DEFAULT 8,
  hp INTEGER NOT NULL DEFAULT 20 CHECK (hp BETWEEN 0 AND 20),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(session_id, client_key)
);
GRANT SELECT ON public.exploration_players TO anon, authenticated;
GRANT ALL ON public.exploration_players TO service_role;
ALTER TABLE public.exploration_players ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Exploration players are publicly visible" ON public.exploration_players FOR SELECT TO anon, authenticated USING (true);

CREATE TABLE public.exploration_entities (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id UUID NOT NULL REFERENCES public.exploration_sessions(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('enemy', 'trap', 'door', 'event', 'objective')),
  label TEXT NOT NULL,
  tile_x INTEGER NOT NULL,
  tile_y INTEGER NOT NULL,
  hp INTEGER CHECK (hp IS NULL OR hp BETWEEN 0 AND 30),
  locked BOOLEAN NOT NULL DEFAULT false,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
GRANT SELECT ON public.exploration_entities TO anon, authenticated;
GRANT ALL ON public.exploration_entities TO service_role;
ALTER TABLE public.exploration_entities ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Exploration entities are publicly visible" ON public.exploration_entities FOR SELECT TO anon, authenticated USING (true);

CREATE TABLE public.exploration_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id UUID NOT NULL REFERENCES public.exploration_sessions(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  message TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
GRANT SELECT ON public.exploration_events TO anon, authenticated;
GRANT ALL ON public.exploration_events TO service_role;
ALTER TABLE public.exploration_events ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Exploration events are publicly visible" ON public.exploration_events FOR SELECT TO anon, authenticated USING (true);

CREATE INDEX exploration_players_session_idx ON public.exploration_players(session_id);
CREATE INDEX exploration_entities_session_idx ON public.exploration_entities(session_id);
CREATE INDEX exploration_events_session_created_idx ON public.exploration_events(session_id, created_at DESC);

